// Friendly aliases people actually type after the ``` fence.
const ALIASES = {
  js: "javascript", jsx: "javascript", ts: "typescript", py: "python", sh: "bash",
  zsh: "bash", html: "xml", svg: "xml", "c++": "cpp", "c#": "csharp", cs: "csharp",
  rb: "ruby", rs: "rust", yml: "yaml", md: "markdown", ps1: "powershell", tex: "latex",
  docker: "dockerfile", golang: "go", kt: "kotlin",
};

// ---------- placeholders ----------
// Math and videos are generated by us AFTER sanitizing. While parsing, each one is
// replaced by an opaque, per-render random token, then swapped in at the end.

const MAX_SOURCE_CHARS = 900_000;   // GitHub's API won't return files over ~1 MB, so stay under it
const MAX_MATH_ITEMS = 500;         // formulas per document
const MAX_MATH_CHARS = 2000;        // characters per formula
const MAX_HIGHLIGHT_CHARS = 30_000; // very long code blocks are shown plain (keeps the editor responsive)
const MAX_VIDEOS = 20;

let ctx = null; // { nonce, items } for the render currently in progress (render is synchronous)

function randomNonce() {
  const b = new Uint8Array(8);
  crypto.getRandomValues(b);
  return [...b].map((x) => x.toString(16).padStart(2, "0")).join("");
}

function stash(item) {
  const i = ctx.items.push(item) - 1;
  return `PLTOK${ctx.nonce}X${i}PLTOK`;
}

function escapeText(s) {
  return String(s).replace(/[&<>"']/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch]));
}

const mathCount = () => ctx.items.filter((x) => x.type === "math").length;
const videoCount = () => ctx.items.filter((x) => x.type === "video").length;

// ---------- math ----------

const mathBlock = {
  name: "mathBlock",
  level: "block",
  start: (src) => src.indexOf("$$"),
  tokenizer(src) {
    const m = /^\$\$[ \t]*\n?([\s\S]+?)\n?[ \t]*\$\$[ \t]*(?:\n|$)/.exec(src);
    if (m) return { type: "mathBlock", raw: m[0], text: m[1].trim() };
  },
  renderer(t) {
    if (t.text.length > MAX_MATH_CHARS || mathCount() >= MAX_MATH_ITEMS) return `<pre><code>${escapeText(`$$${t.text}$$`)}</code></pre>\n`;
    return `<div class="math-display">${stash({ type: "math", tex: t.text, display: true })}</div>\n`;
  },
};

const mathInline = {
  name: "mathInline",
  level: "inline",
  start: (src) => src.indexOf("$"),
  tokenizer(src) {
    // "$5 and $10" is NOT math: the opening $ must be followed by a non-space,
    // the closing $ must follow a non-space and must not be followed by a digit.
    const m = /^\$(?!\s)((?:\\.|[^$\\\n])+?)(?<!\s)\$(?!\d)/.exec(src);
    if (m) return { type: "mathInline", raw: m[0], text: m[1] };
  },
  renderer(t) {
    if (t.text.length > MAX_MATH_CHARS || mathCount() >= MAX_MATH_ITEMS) return escapeText(`$${t.text}$`);
    return stash({ type: "math", tex: t.text, display: false });
  },
};

// ---------- YouTube ----------
// Raw <iframe> is never allowed through. Instead, a YouTube address is recognised, its 11-character
// video id is checked, and WE build the iframe: fixed host (youtube-nocookie.com), fixed attributes,
// sandboxed. Two ways to embed:
//   1. Paste a YouTube link on a line by itself (watch, youtu.be, shorts, live or embed links)
//   2. Paste YouTube's own "Embed" code; it is converted to the same safe iframe

const YT_ID = /^[A-Za-z0-9_-]{11}$/;
const YT_HOSTS = new Set(["www.youtube.com", "youtube.com", "m.youtube.com", "www.youtube-nocookie.com", "youtube-nocookie.com", "youtu.be"]);

function parseStart(v) {
  if (!v) return 0;
  if (/^\d{1,6}$/.test(v)) return Math.min(Number(v), 86399);
  const m = /^(?:(\d{1,2})h)?(?:(\d{1,3})m)?(?:(\d{1,5})s?)?$/.exec(v);
  if (!m) return 0;
  return Math.min((Number(m[1] || 0) * 3600) + (Number(m[2] || 0) * 60) + Number(m[3] || 0), 86399);
}

/** Returns { id, start } for a YouTube video address, or null. Never throws. */
function parseYoutube(href) {
  let u;
  try { u = new URL(String(href).trim(), "https://invalid.example"); } catch { return null; }
  if (u.protocol !== "https:" && u.protocol !== "http:") return null;
  if (!YT_HOSTS.has(u.hostname.toLowerCase())) return null;
  let id = null;
  if (u.hostname.toLowerCase() === "youtu.be") id = u.pathname.slice(1).split("/")[0];
  else if (u.pathname === "/watch") id = u.searchParams.get("v");
  else {
    const m = /^\/(?:embed|shorts|live|v)\/([^/?#]+)/.exec(u.pathname);
    if (m) id = m[1];
  }
  if (!id || !YT_ID.test(id)) return null;
  const start = parseStart(u.searchParams.get("t") || u.searchParams.get("start") || (u.hash.match(/^#t=(.+)$/) || [])[1]);
  return { id, start };
}

function videoHtml({ id, start }) {
  const q = new URLSearchParams({ rel: "0" });
  if (start) q.set("start", String(start));
  return `<iframe src="https://www.youtube-nocookie.com/embed/${id}?${q}" title="YouTube video player" loading="lazy" allowfullscreen ` +
    `referrerpolicy="strict-origin-when-cross-origin" ` +
    `sandbox="allow-scripts allow-same-origin allow-presentation allow-popups allow-popups-to-escape-sandbox" ` +
    `allow="accelerometer; encrypted-media; gyroscope; picture-in-picture; fullscreen"></iframe>`;
}

const youtubeBlock = {
  name: "youtubeBlock",
  level: "block",
  tokenizer(src) {
    const m = /^[ \t]*<?(https?:\/\/[^\s<>]+)>?[ \t]*(?:\n|$)/.exec(src);
    if (!m) return;
    const v = parseYoutube(m[1]);
    if (v) return { type: "youtubeBlock", raw: m[0], video: v };
  },
  renderer(t) {
    if (videoCount() >= MAX_VIDEOS) return "";
    return `<div class="video-embed">${stash({ type: "video", ...t.video })}</div>\n`;
  },
};

/** Before sanitizing: turn pasted YouTube <iframe> embed code into placeholders; leave every other iframe for the sanitizer to delete. */
function liftYoutubeIframes(html) {
  if (!/<iframe/i.test(html)) return html;
  const doc = new DOMParser().parseFromString(html, "text/html");
  for (const f of doc.querySelectorAll("iframe")) {
    const v = parseYoutube(f.getAttribute("src") || "");
    if (v && videoCount() < MAX_VIDEOS) {
      const box = doc.createElement("div");
      box.className = "video-embed";
      box.append(doc.createTextNode(stash({ type: "video", ...v })));
      f.replaceWith(box);
    }
  }
  return doc.body.innerHTML;
}

// ---------- marked instance ----------

const md = new Marked({ gfm: true, breaks: false });
md.use({
  extensions: [youtubeBlock, mathBlock, mathInline],
  renderer: {
    // Code is escaped by hljs (or by us for unknown languages), then sanitized again below.
    code(code, infostring) {
      const lang = ((infostring || "").match(/^\S+/) || [""])[0].toLowerCase();
      const name = ALIASES[lang] || lang;
      let inner;
      let cls = "hljs";
      if (name && code.length <= MAX_HIGHLIGHT_CHARS && hljs.getLanguage(name)) {
        inner = hljs.highlight(code, { language: name, ignoreIllegals: true }).value;
        cls += ` language-${name}`;
      } else {
        inner = escapeText(code);
      }
      return `<pre><code class="${cls}">${inner}</code></pre>\n`;
    },
  },
});

// ---------- sanitizer ----------

const purifier = DOMPurify; // single shared instance, configured once below

purifier.addHook("afterSanitizeAttributes", (node) => {
  if (node.tagName === "A" && node.getAttribute("href")) {
    const href = node.getAttribute("href");
    if (/^https?:/i.test(href)) node.setAttribute("rel", "noopener noreferrer");
  }
  if (node.tagName === "IMG") {
    node.setAttribute("loading", "lazy");
    node.setAttribute("referrerpolicy", "no-referrer");
  }
});

const PURIFY_CONFIG = {
  USE_PROFILES: { html: true },
  FORBID_TAGS: ["style", "form", "input", "button", "textarea", "select", "option", "iframe",
    "frame", "frameset", "object", "embed", "applet", "link", "meta", "base", "script", "noscript", "template"],
  FORBID_ATTR: ["style", "srcdoc", "formaction", "ping"],
  ALLOW_DATA_ATTR: false,
  ALLOW_ARIA_ATTR: true,
  SANITIZE_DOM: true,
  // id= and name= values get a "user-content-" prefix, so a post can never take over an id or
  // global name the editor itself relies on (DOM clobbering).
  SANITIZE_NAMED_PROPS: true,
};

/** Sanitize an HTML string. Exposed so any other HTML we ever display goes through the same rules. */
export function sanitizeHtml(html) {
  return purifier.sanitize(html, PURIFY_CONFIG);
}

