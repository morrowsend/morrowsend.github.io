// render.js
// The ONE place Markdown becomes HTML. Both the live preview and the published
// pages go through renderMarkdown(), so what you see is what gets published, and
// there is exactly one place to audit for security.
//
// Pipeline:
//   1. marked parses Markdown. Code blocks are syntax-highlighted (highlight.js),
//      and $math$ is swapped for an opaque random placeholder.
//   2. DOMPurify sanitizes the whole result (strips scripts, event handlers,
//      javascript: URLs, iframes, forms, inline styles ...).
//   3. Only AFTER sanitizing, placeholders are replaced with KaTeX output.
//      KaTeX output is generated by us from the math text, never from raw HTML
//      the author typed, so it can't smuggle anything through.

