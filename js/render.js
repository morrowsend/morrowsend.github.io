/**
 * @param {string} markdown
 * @returns {{ html: string, excerpt: string, hasMath: boolean, hasVideo: boolean }}
 * @throws if the source is longer than the publishing limit
 */
export function renderMarkdown(markdown) {
  const source = String(markdown ?? "");
  if (source.length > MAX_SOURCE_CHARS) {
    throw new Error(`This is too long to publish (${source.length.toLocaleString()} characters; the limit is ${MAX_SOURCE_CHARS.toLocaleString()}). Split it into two posts.`);
  }
  ctx = { nonce: randomNonce(), items: [] };
  const { nonce, items } = ctx;
  let clean;
  try {
    clean = sanitizeHtml(liftYoutubeIframes(md.parse(source)));
  } finally {
    ctx = null;
  }

  // Work on an inert DOM (nothing in it executes or loads).
  const doc = new DOMParser().parseFromString(clean, "text/html");
  const tokenRe = new RegExp(`PLTOK${nonce}X(\\d+)PLTOK`, "g");

  // Excerpt: plain text of the sanitized page with math and videos removed.
  const excerpt = (doc.body.textContent || "")
    .replace(tokenRe, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 160);

  // Swap placeholders for generated HTML in TEXT NODES ONLY, so a placeholder that somehow
  // ended up inside an attribute value can never be expanded into markup.
  const walker = doc.createTreeWalker(doc.body, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) if (walker.currentNode.data.includes(`PLTOK${nonce}X`)) textNodes.push(walker.currentNode);
  for (const node of textNodes) {
    let out = "";
    let last = 0;
    const data = node.data;
    for (const m of data.matchAll(tokenRe)) {
      out += escapeText(data.slice(last, m.index));
      const item = items[Number(m[1])];
      if (item?.type === "math") {
        out += katex.renderToString(item.tex, {
          displayMode: item.display,
          throwOnError: false,
          trust: false,
          strict: "ignore",
          maxExpand: 1000,
          maxSize: 50,
          output: "htmlAndMathml",
        });
      } else if (item?.type === "video") {
        out += videoHtml(item);
      }
      last = m.index + m[0].length;
    }
    out += escapeText(data.slice(last));
    const holder = doc.createElement("span");
    holder.innerHTML = out;
    node.replaceWith(...holder.childNodes);
  }
  const html = doc.body.innerHTML;

  return {
    html,
    excerpt,
    hasMath: items.some((x) => x.type === "math"),
    hasVideo: items.some((x) => x.type === "video"),
  };
}
